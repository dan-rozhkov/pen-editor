#!/usr/bin/env node
// Regenerates src/components/brand/sideformLogoPaths.ts from the canonical logo
// SVGs in public/brand/ (approved variant 06). Run after replacing those files:
//   node scripts/generate-sideform-logo.mjs
// SideformLogo.test.tsx fails if the module and the SVGs drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Every <path> of a flat, currentColor-only SVG: d, translate offset, even-odd flag. */
export function parseLogoSvg(svg) {
  if (/<(g|image|text|use)\b/.test(svg)) throw new Error("logo SVG must contain only flat <path> elements");
  return [...svg.matchAll(/<path\b[^>]*?\/>/gs)].map(([tag]) => {
    const attrs = Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
    const unknown = Object.keys(attrs).filter((k) => !["d", "fill", "transform", "fill-rule"].includes(k));
    if (unknown.length || attrs.fill !== "currentColor") throw new Error(`unexpected path attributes: ${tag.slice(0, 80)}`);
    let x = "0";
    let y = "0";
    if (attrs.transform) {
      const m = /^translate\(([-\d.]+),([-\d.]+)\)$/.exec(attrs.transform);
      if (!m) throw new Error(`unsupported transform: ${attrs.transform}`);
      [, x, y] = m;
    }
    return { d: attrs.d.trim(), x, y, evenOdd: attrs["fill-rule"] === "evenodd" };
  });
}

function entry(p) {
  return `{ d: "${p.d}", x: ${p.x}, y: ${p.y}${p.evenOdd ? ", evenOdd: true" : ""} }`;
}

function main() {
  const lockup = parseLogoSvg(readFileSync(resolve(root, "public/brand/sideform-lockup.svg"), "utf8"));
  const mark = parseLogoSvg(readFileSync(resolve(root, "public/brand/sideform-mark.svg"), "utf8"));
  if (mark.length !== 1 || entry(mark[0]) !== entry(lockup[0])) {
    throw new Error("sideform-mark.svg must be exactly the first path of sideform-lockup.svg");
  }
  const lines = [
    "// GENERATED by scripts/generate-sideform-logo.mjs from public/brand/sideform-{lockup,mark}.svg",
    "// (approved variant 06). Do not edit by hand or retype the wordmark as text: every glyph is an",
    "// outlined path. Path data, translate offsets and fill-rule are copied verbatim from the SVGs.",
    "",
    "export type LogoPath = { readonly d: string; readonly x: number; readonly y: number; readonly evenOdd?: boolean };",
    "",
    "/** The approved mark, in the lockup's coordinate space (fits viewBox 0 0 157 217). */",
    `export const SIDEFORM_MARK_PATH: LogoPath = ${entry(lockup[0])};`,
    "",
    '/** The "Sideform" wordmark glyphs, right of the mark (lockup viewBox 0 0 911 217), in source order. */',
    "export const SIDEFORM_WORDMARK_PATHS: readonly LogoPath[] = [",
    ...lockup.slice(1).map((p) => `  ${entry(p)},`),
    "];",
    "",
    "export const SIDEFORM_MARK_VIEWBOX = { width: 157, height: 217 } as const;",
    "export const SIDEFORM_LOCKUP_VIEWBOX = { width: 911, height: 217 } as const;",
    "",
  ];
  writeFileSync(resolve(root, "src/components/brand/sideformLogoPaths.ts"), lines.join("\n"));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
