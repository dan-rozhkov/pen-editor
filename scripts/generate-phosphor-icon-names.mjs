#!/usr/bin/env node
/**
 * Regenerate src/lib/embedHtmlLint/phosphorIconNames.ts from the Phosphor web
 * stylesheet the prototype/slides skills tell the agent to @import.
 *
 *   node scripts/generate-phosphor-icon-names.mjs [version]
 *
 * Keep the version in step with the @import URL in src/skills/prototype.md
 * (pen-editor-backend) — the list is only useful if it matches what loads.
 */
import { writeFile } from "node:fs/promises";

const version = process.argv[2] ?? "2.1.1";
const url = `https://unpkg.com/@phosphor-icons/web@${version}/src/regular/style.css`;

const css = await fetch(url).then((r) => {
  if (!r.ok) throw new Error(`${url} → ${r.status}`);
  return r.text();
});

const names = [...new Set([...css.matchAll(/\.ph\.ph-([a-z0-9-]+)/g)].map((m) => m[1]))].sort();
if (names.length < 500) throw new Error(`only ${names.length} icon names parsed — stylesheet shape changed?`);

const lines = [];
let cur = "";
for (const name of names) {
  const token = `"${name}",`;
  if (cur.length + token.length + 2 > 100) {
    lines.push(`  ${cur.trimEnd()}`);
    cur = "";
  }
  cur += `${token} `;
}
if (cur) lines.push(`  ${cur.trimEnd()}`);

await writeFile(
  new URL("../src/lib/embedHtmlLint/phosphorIconNames.ts", import.meta.url),
  `/**
 * Icon names shipped by \`@phosphor-icons/web@${version}\` (the \`regular\` stylesheet the
 * prototype/slides skills tell the agent to \`@import\`), without the \`ph-\` prefix.
 *
 * Generated by \`scripts/generate-phosphor-icon-names.mjs\` from that stylesheet's
 * own class list — regenerate it whenever the pinned Phosphor version changes.
 * A name missing here renders as blank space in an embed with no error anywhere,
 * which is why ${names.length} strings are worth checking in.
 */
export const PHOSPHOR_WEB_VERSION = "${version}";

export const PHOSPHOR_ICON_NAMES: ReadonlySet<string> = new Set([
${lines.join("\n")}
]);
`,
);
console.log(`wrote ${names.length} icon names from ${url}`);
